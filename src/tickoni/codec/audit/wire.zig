/// Wire-format codec for audit events.
///
/// All struct types are generated from the C header via translate-c —
/// no hand-written mirrors. Alignment is guaranteed by the C compiler.
const std = @import("std");
const audit_schema = @import("audit_schema");
// C types from translate-c, re-exported by audit_schema.
const c_schema = audit_schema.c_schema;

pub const status_ok: c_int = 0;
pub const status_no_space: c_int = 1;
pub const status_invalid_protobuf: c_int = 2;
pub const status_invalid_json: c_int = 3;
pub const status_invalid_field: c_int = 4;

// ─── Wire types (re-exported from translate-c — autogenerated) ───
// These are extern structs generated from audit_schema.h by translate-c.
// The _pad fields ensure correct C ABI alignment — we don't define them.

/// Wire-format header — exact layout from C AuditHeader.
pub const Header = c_schema.AuditHeader;

/// Wire-format payloads — autogenerated from C types.
pub const SourceEventPayload = c_schema.WireSourceEventPayload;
pub const NormalizationPayload = c_schema.WireNormalizationPayload;
/// PolicyDecisionPayload: same struct used in both runtime and wire format.
pub const PolicyDecisionPayload = c_schema.PolicyDecisionPayload;

fn parseEnumByValue(comptime T: type, value: anytype) error{ UnknownRecordType, UnknownEnumValue }!T {
    const e = @typeInfo(T).@"enum";
    inline for (e.field_names, e.field_values) |name, field_value| {
        if (field_value == value) return @field(T, name);
    }
    if (T == audit_schema.RecordType) return error.UnknownRecordType;
    return error.UnknownEnumValue;
}

// ─── Mechanical sync check ───
// Wire types are autogenerated from C — the Payload union field names
// must match. This is the prerequisite check for finding 32 in
// doc/strategy/roadmap/backlog/audits/tech_debt.md.
test "wire Payload union field names match canonical schema" {
    comptime {
        const wire_names = std.meta.fieldNames(Payload);
        const expected_names = [_][]const u8{
            "source_event",
            "normalization",
            "policy_decision",
            "model_call",
            "financial_adapter_call",
            "proposal",
            "destination_check",
            "limit_check",
            "approval_required",
            "denial",
            "telemetry_checkpoint",
            "replay_result",
            "deduplication",
            "case_creation",
        };
        if (wire_names.len != expected_names.len) {
            @compileError("wire Payload union has " ++ std.fmt.bufPrint(
                "expected {d} variants, got {d}",
                .{ expected_names.len, wire_names.len },
            ) ++ " variants");
        }
        var i: usize = 0;
        while (i < wire_names.len) : (i += 1) {
            if (!std.mem.eql(u8, wire_names[i], expected_names[i])) {
                @compileError("wire Payload union variant mismatch at index " ++ std.fmt.bufPrint("{d}", .{i}) ++ ": expected " ++ expected_names[i] ++ " got " ++ wire_names[i]);
            }
        }
    }
}
